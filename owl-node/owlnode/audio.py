"""The `audio` role: AES67 in the host's PipeWire graph, one small client process per job (N1's proven pattern).

  base       PTP driver node (the NIC's PHC, group pipewire.ptp0) + SAP announcer for our senders
  tx-<key>   one rtp-sink per sender: an Audio/Sink "Network TX: ..." that host apps play into
  rx-<key>   one rtp-source per *active* receiver: an Audio/Source; started, stopped and re-targeted from the
             IS-05 active state the agent writes to state.json (so it also comes back after a reboot)

The processes are the image's own `pipewire` binary (PipeWire 1.6 on both arches) connecting to the host's daemon
through the mounted socket, so the streams are ordinary host devices and nothing touches the host's PipeWire or
WirePlumber config. Receivers: sess.latency.msec 6 (N1), adaptive playout by default (see config.ts_direct), and every AES67 stream
pins the PTP graph to 128 frames (N1: 64 frames caused deadline misses on the Pi 5).
"""
import hashlib, json, os, signal, stat, subprocess, sys, time

from . import config
from .config import read_json

PW_DIR = os.path.join(config.RUN_DIR, "pw")
TS_DIRECT = [False]   # decided once at start (host daemon version), see main()
RTP = {}   # node.name -> what PipeWire really sends (payload type, ts-offset, refclk): the SDP must match it


def log(*a):
    print(time.strftime("%H:%M:%S"), "audio:", *a, flush=True)


def esc(s):
    return json.dumps(str(s))          # SPA-JSON accepts JSON strings


def base_conf(n):
    if n.phc_if:
        clock = f"""clock.name = "clock.system.ptp0"
            clock.interface = {esc(n.phc_if)}"""
    else:
        clock = f"""clock.name = "clock.system.{n.system_clock}"
            clock.id = {esc(n.system_clock)}"""
    mgmt = ""
    try:
        sock = stat.S_ISSOCK(os.stat("/var/run/ptp4lro").st_mode)
    except OSError:
        sock = False
    if sock:
        mgmt = 'ptp.management-socket = "/var/run/ptp4lro"'
    sap = ""
    if n.sap:   # announce our senders (Dante Controller / other AES67 gear see them); never auto-create receivers
        sap = f"""    {{ name = libpipewire-module-rtp-sap
        args = {{
            local.ifname = {esc(n.media_if)}
            sap.ip = 239.255.255.255
            sap.port = 9875
            net.ttl = {n.ttl}
            net.loop = {str(n.loopback).lower()}
            {mgmt}
            stream.rules = [
                {{ matches = [ {{ sess.sap.announce = true }} ] actions = {{ announce-stream = {{ }} }} }}
            ]
        }}
    }}"""
    return f"""# owl-node base process for {n.name} (generated by owlnode.audio; do not edit)
context.properties = {{ }}
context.spa-libs = {{ support.* = support/libspa-support }}
context.objects = [
    {{ factory = spa-node-factory
        args = {{
            factory.name    = support.node.driver
            node.name       = PTP0-Driver
            node.group      = pipewire.ptp0
            priority.driver = 100000
            {clock}
            resync.ms       = 1.5
            object.export   = true
        }}
    }}
]
context.modules = [
    {{ name = libpipewire-module-rt args = {{ nice.level = -11 }} flags = [ ifexists nofail ] }}
    {{ name = libpipewire-module-protocol-native }}
    {{ name = libpipewire-module-client-node }}
    {{ name = libpipewire-module-spa-node-factory }}
    {{ name = libpipewire-module-adapter }}
{sap}
]
"""


COMMON = """context.properties = { }
context.spa-libs = { support.* = support/libspa-support  audio.convert.* = audioconvert/libspa-audioconvert }
context.modules = [
    { name = libpipewire-module-rt args = { nice.level = -11 } flags = [ ifexists nofail ] }
    { name = libpipewire-module-protocol-native }
    { name = libpipewire-module-client-node }
    { name = libpipewire-module-adapter }
"""


def positions(ch):
    return {1: "[ MONO ]", 2: "[ FL FR ]"}.get(ch, "[ " + " ".join(f"AUX{i}" for i in range(ch)) + " ]")


def has_ptp_mgmt():
    try:
        return stat.S_ISSOCK(os.stat("/var/run/ptp4lro").st_mode)
    except OSError:
        return False


def tx_conf(n, s, tp):
    names = {1: '[ "M" ]', 2: '[ "L", "R" ]'}.get(s["channels"], "[ " + ", ".join(f'"{i + 1}"' for i in range(s["channels"])) + " ]")
    return f"""# owl-node sender {s['key']} of {n.name} (generated; do not edit)
{COMMON}    {{ name = libpipewire-module-rtp-sink
        args = {{
            local.ifname = {esc(n.media_if)}
            source.ip = {esc(tp.get('source_ip') or n.ip)}
            destination.ip = {esc(tp.get('destination_ip') or s['group'])}
            destination.port = {int(tp.get('destination_port') or s['port'])}
            net.mtu = 1280
            net.ttl = {n.ttl}
            net.loop = {str(n.loopback).lower()}
            sess.min-ptime = 1
            sess.max-ptime = 1
            sess.name = {esc(s['session'])}
            sess.media = "audio"
            sess.ts-refclk = "ptp=traceable"
            sess.ts-offset = 0
            sess.latency.msec = 3
            audio.format = "S24BE"
            audio.rate = 48000
            audio.channels = {s['channels']}
            audio.position = {positions(s['channels'])}
            node.channel-names = {names}
            stream.props = {{
                node.name = {esc(s['node'])}
                node.description = {esc(s['description'])}
                media.class = "Audio/Sink"
                node.virtual = false
                device.api = aes67
                sess.sap.announce = {str(n.sap).lower()}
                node.always-process = true
                node.group = pipewire.ptp0
                node.force-quantum = {n.quantum}
                priority.session = 0
                rtp.ntp = 0
                rtp.fetch-ts-refclk = {str(has_ptp_mgmt()).lower()}   # needs ptp4l's ro socket (linuxptp >= 4); else SAP cannot build an SDP
                owl.node.id = {esc(s['id'])}
            }}
        }}
    }}
]
"""


def rx_conf(n, r, a):
    tp = a["transport_params"][0]
    f = a.get("format") or {}
    enc = f.get("encoding") or "L24"
    ch = int(f.get("channels") or r["channels"])
    sender = f.get("session") or tp.get("multicast_ip")
    return f"""# owl-node receiver {r['key']} of {n.name} <- {sender} (generated; do not edit)
{COMMON}    {{ name = libpipewire-module-rtp-source
        args = {{
            local.ifname = {esc(n.media_if)}
            source.ip = {esc(tp['multicast_ip'])}
            source.port = {int(tp.get('destination_port') or 5004)}
            sess.latency.msec = {r['latency_ms']:g}
            sess.ts-direct = {str(TS_DIRECT[0]).lower()}
            sess.ignore-ssrc = true
            audio.format = "{'S24BE' if enc == 'L24' else 'S16BE'}"
            audio.rate = {int(f.get('rate') or 48000)}
            audio.channels = {ch}
            audio.position = {positions(ch)}
            stream.props = {{
                node.name = {esc(r['node'])}
                node.description = {esc(f"AES67 RX {r['label']} <- {sender}")}
                media.class = "Audio/Source"
                node.virtual = false
                device.api = aes67
                node.group = pipewire.ptp0
                node.force-quantum = {n.quantum}
                priority.session = 0
                node.autoconnect = false
                owl.node.id = {esc(r['id'])}
                owl.sender.id = {esc(a.get('sender_id') or '')}
            }}
        }}
    }}
]
"""


class Proc:
    def __init__(self, name, conf):
        self.name, self.conf, self.p, self.since, self.restarts, self.next_try = name, conf, None, None, 0, 0
        self.path = os.path.join(PW_DIR, f"{name}.conf")

    @property
    def digest(self):
        return hashlib.sha1(self.conf.encode()).hexdigest()[:10]

    def running(self):
        return self.p is not None and self.p.poll() is None

    def start(self):
        config.atomic_write(self.path, self.conf)
        log(f"start {self.name} ({self.digest})")
        self.p = subprocess.Popen(["pipewire", "-c", self.path], stdout=sys.stdout, stderr=sys.stderr,
                                  start_new_session=True)
        self.since = time.time()

    def stop(self):
        if self.p and self.p.poll() is None:
            log(f"stop {self.name}")
            self.p.terminate()
            try:
                self.p.wait(5)
            except subprocess.TimeoutExpired:
                self.p.kill()
                self.p.wait()
        self.p = None

    def check(self):
        """Restart after an exit, with backoff (2, 4, ... 30 s)."""
        if self.running():
            if time.time() - self.since > 60:
                self.restarts = 0
            return
        if self.p is not None:
            log(f"{self.name} exited with {self.p.returncode}")
            self.p = None
            self.restarts += 1
            self.next_try = time.time() + min(30, 2 ** self.restarts)
        if time.time() >= self.next_try:
            self.start()

    def info(self):
        return {"running": self.running(), "pid": self.p.pid if self.running() else None,
                "up_s": round(time.time() - self.since) if self.running() else 0, "restarts": self.restarts,
                "conf": self.digest}


def pw_nodes():
    try:
        out = subprocess.run(["pw-dump", "--no-colors"], capture_output=True, timeout=10, text=True).stdout
        objs = json.loads(out or "[]")
    except Exception:
        return None, {}
    nodes, ports = {}, {}
    for o in objs:
        if o.get("type") == "PipeWire:Interface:Node":
            props = (o.get("info") or {}).get("props") or {}
            nodes[props.get("node.name")] = o["id"]
            if props.get("rtp.ssrc") is not None:
                RTP[props.get("node.name")] = {k: props.get("rtp." + k) for k in
                                                ("payload", "ssrc", "ts-offset", "ts-refclk", "destination.ip")}
    for o in objs:
        if o.get("type") == "PipeWire:Interface:Port":
            pr = (o.get("info") or {}).get("props") or {}
            ports.setdefault(pr.get("node.id"), []).append((pr.get("port.direction"), pr.get("port.name"), pr.get("port.id")))
    return nodes, ports


def ensure_links(src_node, dst_node, nodes, ports):
    """Link src's output ports to dst's input ports in order (monitor ports excluded)."""
    if src_node not in nodes or dst_node not in nodes:
        return False
    outs = sorted([p for p in ports.get(nodes[src_node], []) if p[0] == "out" and not (p[1] or "").startswith("monitor")], key=lambda p: p[2])
    ins = sorted([p for p in ports.get(nodes[dst_node], []) if p[0] == "in"], key=lambda p: p[2])
    for o, i in zip(outs, ins):
        subprocess.run(["pw-link", f"{src_node}:{o[1]}", f"{dst_node}:{i[1]}"], capture_output=True, timeout=5)
    return True


def main():
    n = config.Node()
    os.makedirs(PW_DIR, exist_ok=True)
    ver = subprocess.run(["pipewire", "--version"], capture_output=True, text=True).stdout.split("\n")
    ver = next((l.split()[-1] for l in ver if l.startswith("Compiled")), "?")
    log(f"node {n.name}: media {n.media_if} ({n.ip}), clock {'PHC of ' + n.phc_if if n.phc_if else 'system ' + n.system_clock}, "
        f"PipeWire {ver}, remote {os.environ.get('PIPEWIRE_RUNTIME_DIR') or os.environ.get('XDG_RUNTIME_DIR')}")
    host = ""
    try:
        out = subprocess.run(["pw-cli", "info", "0"], capture_output=True, text=True, timeout=10).stdout
        host = next((l.split('"')[1] for l in out.splitlines() if l.strip().startswith("version:")), "")
    except Exception:
        pass
    same = host.split(".")[:2] == ver.split(".")[:2]
    # "auto": only with a PHC driver and a host daemon of the image's major.minor (a 1.6 client under pinode's 1.2.7
    # daemon always played silence); even then it was unreliable across restarts, hence the default "false"
    TS_DIRECT[0] = {"true": True, "false": False}.get(n.ts_direct, bool(n.phc_if) and same)
    log(f"host PipeWire daemon {host or '?'}; receivers use {'timestamp-direct' if TS_DIRECT[0] else 'adaptive'} playout"
        f" (ts_direct: {n.ts_direct})")
    base = Proc("base", base_conf(n))
    procs = {}
    stopping = []

    def stop(*_):
        stopping.append(1)
    signal.signal(signal.SIGTERM, stop)
    signal.signal(signal.SIGINT, stop)

    last_mtime, last_dump, nodes = None, 0, {}
    while not stopping:
        base.check()
        try:
            mt = os.stat(config.STATE).st_mtime
        except OSError:
            mt = None
        st = read_json(config.STATE, {}) or {}
        want = {}
        for s in n.senders:
            a = (st.get("senders") or {}).get(s["key"]) or {"master_enable": True, "transport_params": [{}]}
            tp = a["transport_params"][0]
            if a.get("master_enable", True) and tp.get("rtp_enabled", True):
                want[f"tx-{s['key']}"] = tx_conf(n, s, tp)
        for r in n.receivers:
            a = (st.get("receivers") or {}).get(r["key"])
            if not a:
                continue
            tp = a["transport_params"][0]
            if a.get("master_enable") and tp.get("rtp_enabled") and tp.get("multicast_ip"):
                want[f"rx-{r['key']}"] = rx_conf(n, r, a)
        if mt != last_mtime:
            last_mtime = mt
        for name in list(procs):
            if name not in want or procs[name].conf != want[name]:
                procs.pop(name).stop()
        if base.running() and time.time() - base.since > 1.0:
            for name, conf in want.items():
                if name not in procs:
                    procs[name] = Proc(name, conf)
                procs[name].check()
        if time.time() - last_dump > 5:
            last_dump = time.time()
            nodes, ports = pw_nodes()
            nodes = nodes or {}
            for r in n.receivers:
                if r.get("link_to") and f"rx-{r['key']}" in procs:
                    ensure_links(r["node"], r["link_to"], nodes, ports)
            for s in n.senders:
                if s.get("link_from") and f"tx-{s['key']}" in procs:
                    ensure_links(s["link_from"], s["node"], nodes, ports)
            status = {"time": time.time(), "pipewire": ver, "host_pipewire": host, "ts_direct": TS_DIRECT[0], "base": dict(base.info(), driver_present="PTP0-Driver" in nodes),
                      "senders": {s["key"]: dict(procs[f"tx-{s['key']}"].info(), node_present=s["node"] in nodes,
                                                 rtp=RTP.get(s["node"]))
                                  if f"tx-{s['key']}" in procs else {"running": False} for s in n.senders},
                      "receivers": {r["key"]: dict(procs[f"rx-{r['key']}"].info(), node_present=r["node"] in nodes)
                                    if f"rx-{r['key']}" in procs else {"running": False} for r in n.receivers}}
            config.atomic_write(config.AUDIO_STATUS, status)
        time.sleep(0.25)
    log("stopping all processes")
    for p in procs.values():
        p.stop()
    base.stop()
