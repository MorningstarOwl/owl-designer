"""Block types: one YAML file each (dsp/blocks/*.yaml). Ports, params, PipeWire node names per port, live controls
and a PipeWire config template. The canvas and the compiler know nothing about a particular block; adding one is
adding a file.

Template language (deliberately tiny; configs are SPA-JSON, so no brace-based engine):
  @each(N){ BODY }       BODY repeated N times, `#` = index (N is a number or ch.<port>)
  ${id} ${label}         the block instance
  ${p.NAME}              a param (bools render true/false)
  ${ch.PORT} ${pos.PORT} channel count / position list of a port
  ${lin:X}               10^(X/20)        ${ms2frac:X}  X ms as frames/48000 (echo-cancel's play delay)
  ${ms2s:X}              X ms as seconds  ${bool01:X}  1/0
  ${sel:COND:A:B}        A if COND is truthy else B      ${eq:X:V:A:B}  A if str(X) == V else B
Expressions nest innermost-first: ${sel:p.mute:0:${lin:p.gain_db}}.

Two ways to write a processing block (D2):
  conf: |          the full module entry (D1 style; the AEC, mixer, router and tone do this)
  plugin: {...}    a filter-chain wrapper around ONE plugin (builtin or LADSPA), stereo or one instance per channel,
                   with an optional sidechain input: nodes, live controls and the filter-chain config are generated.
                   The compressor, limiter, EQ, delay and ducker are ~25 lines each; a new LADSPA plugin is a new file.
  objects: |       extra `context.objects` entries for the block process (the App Input block's null sink)
Ubuntu's PipeWire ships filter-graph plugins `builtin` and `ladspa` only (no LV2 loader), so LV2-only plugins (x42,
calf) are out until the image carries a PipeWire built with lilv; LSP is in the image as its LADSPA build.
"""
import glob, json, os, re, sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
BLOCK_DIRS = [d for d in (os.environ.get("OWL_DSP_BLOCKS"), "/opt/owl-node/dsp/blocks",
                          os.path.normpath(os.path.join(HERE, "..", "..", "dsp", "blocks"))) if d]
ID_RE = re.compile(r"^[a-z][a-z0-9-]{0,30}$")
CMD_PREFIX = "#!owl-cmd "        # a block "conf" that is a command line (JSON argv), not a pipewire -c config
VAR_RE = re.compile(r"\$\{([^${}]*)\}")
COMMON = """# owl-node dsp block process (generated by owlnode.dsp; do not edit)
context.properties = { }
context.spa-libs = { support.* = support/libspa-support  audio.convert.* = audioconvert/libspa-audioconvert }
context.modules = [
    { name = libpipewire-module-rt args = { nice.level = -11 } flags = [ ifexists nofail ] }
    { name = libpipewire-module-protocol-native }
    { name = libpipewire-module-client-node }
    { name = libpipewire-module-adapter }
"""


def positions(n):
    return {1: "[ MONO ]", 2: "[ FL FR ]"}.get(n, "[ " + " ".join(f"AUX{i}" for i in range(n)) + " ]")


def fmt(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, float):
        return str(int(v)) if v == int(v) and abs(v) < 1e12 else f"{v:.6g}"
    return str(v)


def truthy(v):
    if isinstance(v, str):
        return v.strip().lower() not in ("", "0", "false", "no", "off", "null", "none")
    return bool(v)


def slug(s):
    s = re.sub(r"[^a-z0-9]+", "_", str(s or "").lower()).strip("_")
    return s or "x"


class Ctx:
    def __init__(self, bid, label, params, channels):
        self.id, self.label, self.params, self.channels = bid, label, params, channels

    def value(self, expr):
        expr = expr.strip()
        if expr == "id":
            return self.id
        if expr == "label":
            return self.label
        if expr.startswith("p."):
            if expr[2:] not in self.params:
                raise KeyError(f"unknown param {expr[2:]!r}")
            return self.params[expr[2:]]
        if expr.startswith("ch."):
            if expr[3:] not in self.channels:
                raise KeyError(f"unknown port {expr[3:]!r}")
            return self.channels[expr[3:]]
        if expr.startswith("pos."):
            return positions(int(self.channels[expr[4:]]))
        if expr in ("true", "false"):
            return expr == "true"
        try:
            return float(expr) if ("." in expr or "e" in expr) else int(expr)
        except ValueError:
            return expr

    def num(self, expr):
        v = self.value(expr)
        return float(v) if not isinstance(v, bool) else (1.0 if v else 0.0)

    def expand(self, expr):
        if ":" not in expr:
            return fmt(self.value(expr))
        fn, rest = expr.split(":", 1)
        if fn == "lin":
            return fmt(round(10 ** (self.num(rest) / 20), 6))
        if fn == "ms2frac":
            return f"{int(round(self.num(rest) * 48))}/48000"
        if fn == "ms2s":
            return fmt(round(self.num(rest) / 1000.0, 6))
        if fn == "bool01":
            return "1" if truthy(self.value(rest)) else "0"
        if fn == "sel":
            cond, a, b = rest.split(":", 2)
            return a if truthy(self.value(cond)) else b
        if fn == "eq":
            x, v, a, b = rest.split(":", 3)
            return a if fmt(self.value(x)) == v else b
        raise KeyError(f"unknown template function {fn!r}")


def expand_each(tpl, ctx):
    out, i = [], 0
    while True:
        j = tpl.find("@each(", i)
        if j < 0:
            out.append(tpl[i:])
            break
        out.append(tpl[i:j])
        k = tpl.index(")", j)
        n = int(ctx.num(tpl[j + 6:k]))
        assert tpl[k + 1] == "{", "@each(N) must be followed by {"
        depth, m = 0, k + 1
        while True:
            c = tpl[m]
            depth += (c == "{") - (c == "}")
            if depth == 0:
                break
            m += 1
        body = tpl[k + 2:m]
        out.append("".join(body.replace("#", str(x)) for x in range(n)))
        i = m + 1
    return "".join(out)


def render(tpl, ctx):
    s = expand_each(tpl, ctx)
    for _ in range(20):
        s2 = VAR_RE.sub(lambda m: ctx.expand(m.group(1)), s)
        if s2 == s:
            return s
        s = s2
    raise ValueError("template did not converge")


def spa_value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return fmt(v)
    return f'"{v}"' if not str(v).startswith("${") else str(v)


def expand_plugin(d, path):
    """The `plugin:` shorthand -> nodes, controls and conf (see the module docstring)."""
    pl = d["plugin"]
    kind = pl.get("type", "ladspa")
    if kind not in ("ladspa", "builtin"):
        raise ValueError(f"{path}: plugin.type must be ladspa or builtin")
    ins, outs = d.get("inputs") or [], d.get("outputs") or []
    main_in = next((p for p in ins if p["id"] != "sidechain"), None)
    sc_in = next((p for p in ins if p["id"] == "sidechain"), None)
    main_out = outs[0] if outs else None
    if not main_in or not main_out or len(outs) != 1:
        raise ValueError(f"{path}: a plugin block has one main input (plus an optional `sidechain`) and one output")
    per_ch = bool(pl.get("per_channel"))
    a_in, a_out, sc_names = pl.get("audio_in") or [], pl.get("audio_out") or [], pl.get("sidechain_in") or []
    if sc_in and not sc_names:
        raise ValueError(f"{path}: a sidechain input needs plugin.sidechain_in port names")
    n_main = "ch." + main_in["id"]
    nodes = {main_in["id"]: {"node": "owl-${id}-in", "dir": "in", "ports": None if not sc_in else list(range(int(main_in.get("channels", 2))))},
             main_out["id"]: {"node": "owl-${id}-out", "dir": "out"}}
    cap_ch = f"${{{n_main}}}"
    cap_pos = None
    if sc_in:
        nm, ns = int(main_in.get("channels", 2)), int(sc_in.get("channels", 2))
        nodes["sidechain"] = {"node": "owl-${id}-in", "dir": "in", "ports": list(range(nm, nm + ns))}
        cap_ch = str(nm + ns)
        # the main input keeps FL/FR so a stream moved onto this sink lands on the program channels; the YAML may map
        # `sidechain` to a node of its own (the ducker does: a null sink linked internally to these channels)
        cap_pos = "[ FL FR SL SR ]" if (nm, ns) == (2, 2) else positions(nm + ns)
    inst = f"{{ type = {kind} " + (f'plugin = "{pl["plugin"]}" ' if kind == "ladspa" else "") + f'label = "{pl["label"]}" '
    if pl.get("config"):
        inst += "config = { " + " ".join(f'"{k}" = {spa_value(v)}' for k, v in pl["config"].items()) + " } "
    ctl = pl.get("controls") or {}
    inst += "control = { " + " ".join(f'"{k}" = {v}' for k, v in ctl.items()) + " } }" if ctl else "}"
    controls = []
    if per_ch:
        if len(a_in) != 1 or len(a_out) != 1:
            raise ValueError(f"{path}: per_channel plugins have one audio_in and one audio_out port")
        graph_nodes = f"@each({n_main}){{ {inst.replace('type =', 'name = f# type =', 1)} }}"
        g_in = f'@each({n_main}){{ "f#:{a_in[0]}" }}'
        g_out = f'@each({n_main}){{ "f#:{a_out[0]}" }}'
        for k, v in ctl.items():
            controls.append({"node": main_in["id"], "each": n_main, "control": f"f#:{k}", "value": v})
    else:
        graph_nodes = inst.replace("type =", "name = f0 type =", 1)
        g_in = " ".join(f'"f0:{p}"' for p in a_in + sc_names)
        g_out = " ".join(f'"f0:{p}"' for p in a_out)
        for k, v in ctl.items():
            controls.append({"node": main_in["id"], "control": f"f0:{k}", "value": v})
    conf = f"""{{ name = libpipewire-module-filter-chain
    args = {{
        node.description = "${{label}}"
        media.name = "${{label}}"
        filter.graph = {{
            nodes = [ {graph_nodes} ]
            inputs = [ {g_in} ]
            outputs = [ {g_out} ]
        }}
        capture.props = {{
            node.name = "owl-${{id}}-in"
            node.description = "${{label}}: in"
            media.class = Audio/Sink
            audio.channels = {cap_ch}
            audio.position = {"${pos." + main_in["id"] + "}" if not sc_in else cap_pos}
            node.autoconnect = false
            priority.session = 0
            owl.dsp.block = "${{id}}"
        }}
        playback.props = {{
            node.name = "owl-${{id}}-out"
            node.description = "${{label}}: out"
            media.class = Audio/Source
            audio.channels = ${{ch.{main_out["id"]}}}
            audio.position = ${{pos.{main_out["id"]}}}
            node.autoconnect = false
            priority.session = 0
            owl.dsp.block = "${{id}}"
        }}
    }}
}}
"""
    return nodes, controls, conf


class BlockType:
    def __init__(self, d, path):
        self.raw, self.path = d, path
        self.type = d["type"]
        if not ID_RE.match(self.type):
            raise ValueError(f"{path}: bad type id {self.type!r}")
        self.label = d.get("label", self.type)
        self.group = d.get("group", "Other")
        self.description = d.get("description", "")
        self.inputs = d.get("inputs") or []
        self.outputs = d.get("outputs") or []
        self.params = d.get("params") or {}
        self.engine = d.get("engine", "pipewire")
        self.restart_on = set(d.get("restart_on") or [])
        self.nodes = d.get("nodes") or {}
        self.controls_def = d.get("controls") or []
        self.conf = d.get("conf") or ""
        self.objects = d.get("objects") or ""
        self.test = d.get("test")            # scripts/checks/dsp-blocks.py reads this
        self.plugin = d.get("plugin")
        # D3 device blocks (engine device): no process; the block IS a PipeWire device node that matches `match:`
        # when plugged in (glob on node.name, exact media.class), plus `setup:` commands run when it is present
        self.match = d.get("match") or {}
        self.setup = d.get("setup") or []
        if self.engine == "device" and not self.match.get("node.name"):
            raise ValueError(f"{path}: a device block needs match: {{node.name: <glob>}}")
        # links between the block's own nodes, made by the deployer like any wire (a sidechain feeder sink -> plugin channels)
        self.internal_links = d.get("internal_links") or []
        if self.plugin:
            nodes, controls, conf = expand_plugin(d, path)
            self.nodes = dict(nodes, **self.nodes)
            self.controls_def = controls + self.controls_def
            self.conf = conf + self.conf
            # every param a control refers to is live unless the file says it restarts the block
            used = set(re.findall(r"p\.([a-z0-9_]+)", " ".join(str(c["value"]) for c in controls)))
            for k in used:
                if k in self.params and k not in self.restart_on:
                    self.params[k].setdefault("live", True)
        for pid in [p["id"] for p in self.inputs + self.outputs]:
            if pid not in self.nodes and self.engine in ("pipewire", "meter"):
                raise ValueError(f"{path}: port {pid!r} has no nodes: entry")

    def defaults(self):
        return {k: v.get("default") for k, v in self.params.items()}

    def coerce(self, params):
        """User params -> typed, with defaults filled in and ranges clamped."""
        out = self.defaults()
        for k, v in (params or {}).items():
            if k not in self.params:
                continue
            spec = self.params[k]
            t = spec.get("type", "number")
            try:
                if t == "bool":
                    v = truthy(v)
                elif t == "int":
                    v = int(round(float(v)))
                elif t == "number":
                    v = float(v)
                elif t == "select":
                    v = str(v)
                    if v not in [str(o) for o in spec.get("options", [])]:
                        v = spec.get("default")
                else:
                    v = str(v)
            except (TypeError, ValueError):
                v = spec.get("default")
            if t in ("int", "number"):
                if "min" in spec:
                    v = max(spec["min"], v)
                if "max" in spec:
                    v = min(spec["max"], v)
            out[k] = v
        return out

    def _channels(self, spec, params):
        if spec.get("media", "audio") != "audio":
            return None
        c = spec.get("channels", 2)
        if isinstance(c, str) and c.startswith("$p."):
            return int(params[c[3:]])
        return int(c)

    def ports(self, params):
        mk = lambda p: {"id": p["id"], "label": p.get("label", p["id"]), "media": p.get("media", "audio"),
                        "channels": self._channels(p, params) if p.get("media", "audio") == "audio" else None}
        return {"inputs": [mk(p) for p in self.inputs], "outputs": [mk(p) for p in self.outputs]}

    def ctx(self, bid, label, params):
        params = self.coerce(params)
        ch = {p["id"]: self._channels(p, params) for p in self.inputs + self.outputs}
        return Ctx(bid, label or self.label, params, ch)

    def node_map(self, ctx):
        """port id -> {node, dir, ports (channel indexes or None), monitor}"""
        out = {}
        for pid, spec in self.nodes.items():
            out[pid] = {"node": render(spec["node"], ctx), "dir": spec.get("dir", "in"), "ports": spec.get("ports"),
                        "monitor": bool(spec.get("monitor"))}
        return out

    def node_names(self, ctx):
        if self.engine == "rtsp" and not self.render_conf(ctx):
            return []                                  # no audio pulled: no node to wait for
        names = {v["node"] for v in self.node_map(ctx).values()}
        for l in self.internal_links:
            names.add(render(l["from"]["node"], ctx))
            names.add(render(l["to"]["node"], ctx))
        return sorted(names)

    def internal(self, ctx):
        """[{src: {node, monitor, ports}, dst: {node, ports}}] rendered for this instance."""
        return [{"src": {"node": render(l["from"]["node"], ctx), "monitor": bool(l["from"].get("monitor")), "ports": l["from"].get("ports")},
                 "dst": {"node": render(l["to"]["node"], ctx), "ports": l["to"].get("ports")}} for l in self.internal_links]

    def render_conf(self, ctx):
        """The complete `pipewire -c` config of this block's process (F/RTSP: a command line for engine rtsp)."""
        if self.engine == "rtsp":
            p = ctx.params
            if not p.get("audio") or not str(p.get("url") or "").strip():
                return ""
            argv = [sys.executable, "-u", "-m", "owlnode.dsp.rtsp_audio", "--url", str(p["url"]).strip(),
                    "--node", f"owl-{ctx.id}-audio", "--desc", f"{ctx.label}: audio", "--block", ctx.id,
                    "--latency", str(int(p.get("latency_ms") or 200))]
            return CMD_PREFIX + json.dumps(argv)
        if self.engine != "pipewire":
            return ""
        s = COMMON + render(self.conf, ctx) + "\n]\n"
        if self.objects:
            s += "context.objects = [\n" + render(self.objects, ctx) + "\n]\n"
        return s

    def controls(self, ctx):
        """[(node name, control name, value)] for the live controls."""
        nm = self.node_map(ctx)
        out = []
        for c in self.controls_def:
            node = nm[c["node"]]["node"]
            n = int(ctx.num(c["each"])) if c.get("each") else 1
            for i in range(n):
                name = c["control"].replace("#", str(i)) if c.get("each") else c["control"]
                out.append((node, name, float(render(c["value"], ctx))))
        return out

    def live_params(self):
        return {k for k, v in self.params.items() if v.get("live")}

    def palette(self):
        return {"type": self.type, "label": self.label, "group": self.group, "description": self.description,
                "secret_params": sorted(k for k, v in self.params.items() if v.get("secret")),
                "engine": self.engine, "params": self.params, "inputs": self.inputs, "outputs": self.outputs,
                "defaults": self.defaults(), "nodes": {k: v.get("node") for k, v in self.nodes.items()},
                "test": bool(self.test), "match": self.match or None, "hub_only": bool(self.raw.get("hub_only")),
                "triggers": self.raw.get("triggers") or []}

    def setup_cmds(self, ctx, card=None):
        """[(cmd string, params it depends on)] rendered for this instance; ${card} = the ALSA card index."""
        out = []
        for s_ in self.setup:
            cmd = s_.get("cmd") or ""
            if "${card}" in cmd:
                if card is None:
                    continue
                cmd = cmd.replace("${card}", str(card))
            out.append((render(cmd, ctx), list(s_.get("params") or [])))
        return out


def load(dirs=None):
    types, seen = {}, set()
    for d in dirs or BLOCK_DIRS:
        if not os.path.isdir(d) or os.path.realpath(d) in seen:
            continue
        seen.add(os.path.realpath(d))
        for f in sorted(glob.glob(os.path.join(d, "*.yaml"))):
            with open(f) as fh:
                bt = BlockType(yaml.safe_load(fh), f)
            types.setdefault(bt.type, bt)
        if types:
            break           # the first directory that has blocks wins (env override, image, repo)
    return types
